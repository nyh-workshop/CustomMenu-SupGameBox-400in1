def tile(ch):
    rows = [int(x, 16) for x in G.get(ch.upper(), G['?']).split()]
    lo = bytes([(r << 2) & 0xFF for r in rows] + [0])     # 5 pixels wide, 1 pixel margin left, colour 1
    return lo + bytes(8)


def ascii_tiles():
    """256 tiles (4 KiB): tile n = character n for $20-$5F (lower case shares the upper case glyphs)"""
    out = bytearray(0x1000)
    for n in range(0x20, 0x80):
        out[n * 16:n * 16 + 16] = tile(chr(n))
    return out
